def calculate_reference_coincidence_index(stats):
    """Вычисляет эталонный индекс совпадения"""
    coincidence_index = 0
    for symbol in stats.values():
        coincidence_index += (symbol['percent']) ** 2
    return coincidence_index


reference_coincidence_index = calculate_reference_coincidence_index(reference_stats)


def calculate_current_coincidence_index(stats):
    """Вычисляет индекс совпадения для переданной статистики"""
    total = stats['total_symbols']
    symbol_counts = stats['stats']
    coincidence_index = 0
    for symbol in symbol_counts.values():
        coincidence_index += (symbol['count'] * (symbol['count'] - 1)) / (total * (total - 1))
    return coincidence_index


def find_most_frequent_char_shift(text):
    """Находит сдвиг для самого частого символа"""
    stats = symbol_stats(text)['stats']
    print(stats)
    first_key = next(iter(stats))
    shift = rus.index(' ') - rus.index(first_key)
    return shift


def crack_vigenere_key(text):
    """Взламывает ключ шифра Виженера"""
    min_dist = float('inf')
    candidate = 0
    for length in range(3, min(len(text), 10)):
        column = text[::length]
        stats = symbol_stats(column)
        ind = calculate_current_coincidence_index(stats)
        if abs(ind - reference_coincidence_index) < min_dist:
            min_dist = abs(ind - reference_coincidence_index)
            candidate = length
    key = ''
    for i in range(candidate):
        column = text[i::candidate]
        key += rus[-(find_most_frequent_char_shift(column))]
    return key


