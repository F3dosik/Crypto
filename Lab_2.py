def vigenere_cipher(text, key, mode="encrypt"):
    """Шифрует/дешифрует текст методом Виженера"""
    text = keep_russian_letters(text)
    key = keep_russian_letters(key)
    result = ''
    key_position = 0

    if mode == "encrypt":  # Шифрование
        shift_func = lambda p, k: (rus.index(p) + rus.index(k)) % 33
    elif mode == "decrypt":  # Дешифрование
        shift_func = lambda p, k: (rus.index(p) - rus.index(k)) % 33
    else:
        raise ValueError("Режим может быть только encrypt и decrypt")

    for i in range(len(text)):
        p = text[i]
        k = key[key_position]
        result += rus[shift_func(p, k)]
        key_position = (key_position + 1) % len(key)

    return result


